    FOR PR IN C_PRODUCTOS LOOP
        IF PR.PRECIO > V_MAXIMO THEN
            V_MAXIMO      := PR.PRECIO;
            V_ID_PRODUCTO := PR.ID_PRODUCTO;
        END IF;
    END LOOP;
    RETURN V_ID_PRODUCTO;
END FIDE_PRODUCTO_MAS_CARO_CURSOR_FN;

