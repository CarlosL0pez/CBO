--14. Cliente que mas ha gastado 
FUNCTION FIDE_CLIENTE_MAS_GASTADO_CURSOR_FN
RETURN NUMBER IS
    V_ID_CLIENTE NUMBER := 0;
    V_MAXIMO     NUMBER := 0;
    CURSOR C_CLIENTES IS
        SELECT V.ID_CLIENTE, SUM(T.MONTO) TOTAL
        FROM FIDE_VISITAS_TB V, FIDE_SUSCRIPCIONES_TB S, FIDE_TRANSACCIONES_TB T
        WHERE V.ID_SUSCRIPCION = S.ID_SUSCRIPCION
        AND T.ID_PAGO = S.ID_PAGO
        GROUP BY V.ID_CLIENTE;
BEGIN
    FOR CL IN C_CLIENTES LOOP
        IF CL.TOTAL > V_MAXIMO THEN
            V_MAXIMO     := CL.TOTAL;
            V_ID_CLIENTE := CL.ID_CLIENTE;
        END IF;
    END LOOP;
    RETURN V_ID_CLIENTE;
END FIDE_CLIENTE_MAS_GASTADO_CURSOR_FN;

