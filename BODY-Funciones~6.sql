--12. Producto con menor stock (sin parametros)
FUNCTION FIDE_PRODUCTO_MENOR_STOCK_CURSOR_FN
RETURN NUMBER IS
    V_ID_PRODUCTO NUMBER := NULL;
    CURSOR C_PRODUCTOS IS
        SELECT ID_PRODUCTO
        FROM FIDE_PRODUCTOS_TB
        WHERE ID_ESTADO = 1
        ORDER BY UNIDADES_ACTUALES DESC;
BEGIN
    FOR PR IN C_PRODUCTOS LOOP
        V_ID_PRODUCTO := PR.ID_PRODUCTO;
    END LOOP;
    RETURN V_ID_PRODUCTO;
END FIDE_PRODUCTO_MENOR_STOCK_CURSOR_FN;

