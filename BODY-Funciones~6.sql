    V_MAXIMO      NUMBER := 0;
    CURSOR C_PRODUCTOS IS
        SELECT ID_PRODUCTO, PRECIO
        FROM FIDE_PRODUCTOS_TB
        WHERE ID_ESTADO = 1;
